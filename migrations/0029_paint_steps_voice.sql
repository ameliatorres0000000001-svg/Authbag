-- Anajak Secondhand: step-by-step painting cards with pictures and voice, so nobody has to read.
-- Each recipe step: short text, a built-in illustration (icon) or a staff photo, an optional timer, and audio:
-- a staff recording (preferred) or speech generated from the text by Azure Khmer TTS (cached; regenerated
-- only when the text changes). The mixing step is spoken from `mix_text`.
CREATE TABLE paint_recipe_steps (
  id            TEXT PRIMARY KEY,
  recipe_id     TEXT NOT NULL REFERENCES paint_recipes(id) ON DELETE CASCADE,
  sort          INTEGER NOT NULL,
  text          TEXT NOT NULL CHECK (length(trim(text)) BETWEEN 2 AND 500),
  icon          TEXT CHECK (icon IS NULL OR icon IN ('clean','sand','tape','prep','thin_coat','dry','second_coat','edge','finisher','wait','test','polish')),
  minutes       INTEGER CHECK (minutes IS NULL OR minutes BETWEEN 1 AND 1440),
  photo_key     TEXT,
  tts_key       TEXT,
  tts_hash      TEXT,
  voice_key     TEXT,
  voice_mime    TEXT CHECK (voice_mime IS NULL OR voice_mime IN ('audio/wav','audio/mpeg','audio/mp4','audio/webm','audio/ogg')),
  updated_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX idx_paint_steps_recipe ON paint_recipe_steps(recipe_id, sort);

ALTER TABLE paint_recipes ADD COLUMN mix_text TEXT CHECK (mix_text IS NULL OR length(mix_text) <= 500);
ALTER TABLE paint_recipes ADD COLUMN mix_tts_key TEXT;
ALTER TABLE paint_recipes ADD COLUMN mix_tts_hash TEXT;

-- spoken versions of fixed app phrases (scanner guidance), generated by staff in their language
CREATE TABLE ui_voice (
  key        TEXT NOT NULL,
  lang       TEXT NOT NULL CHECK (lang IN ('km','en','vi','th','id')),
  text_hash  TEXT NOT NULL,
  r2_key     TEXT NOT NULL,
  PRIMARY KEY (key, lang)
);
